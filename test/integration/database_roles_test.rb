require "test_helper"

# The app must run as a role that row-level security applies to, and that role must still be able
# to use the tables the owner role creates (ADR-0004, config/database.yml). These tests run the
# role check against real roles: the suite's own, the owner, a superuser, and roles made for one
# test inside a transaction that is rolled back.
class DatabaseRolesTest < ActiveSupport::TestCase
  PROBE_ROLE = "footsoldier_role_check_probe".freeze

  setup { @connections = [] }
  teardown { @connections.each(&:disconnect!) }

  test "the suite connects as the app role, which cannot bypass row-level security" do
    connection = ActiveRecord::Base.lease_connection

    assert_equal "footsoldier_app", connection.select_value("SELECT session_user")
    assert_empty Tenancy::DatabaseRoleCheck.bypass_reasons(connection)
    assert_nothing_raised { Tenancy::DatabaseRoleCheck.verify!(connection) }
  end

  test "the check rejects the owner role" do
    error = with_owner_connection do |connection|
      assert_raises(Tenancy::DatabaseRoleCheck::PrivilegedRoleError) { Tenancy::DatabaseRoleCheck.verify!(connection) }
    end
    assert_match "The database role footsoldier_owner can bypass row-level security", error.message
    assert_match "it has BYPASSRLS", error.message
    assert_match "it owns, or is a member of the owner of,", error.message
    assert_match "public.schema_migrations", error.message
  end

  test "the check rejects a superuser" do
    connection = superuser_connection

    assert_equal [ "it is a superuser" ], Tenancy::DatabaseRoleCheck.bypass_reasons(connection)
    assert_raises(Tenancy::DatabaseRoleCheck::PrivilegedRoleError) { Tenancy::DatabaseRoleCheck.verify!(connection) }
  end

  test "the check rejects a role with BYPASSRLS that owns nothing" do
    as_superuser do |connection|
      connection.execute("CREATE ROLE #{PROBE_ROLE} BYPASSRLS")
      log_in_as(connection, PROBE_ROLE)

      assert_equal [ "it has BYPASSRLS" ], Tenancy::DatabaseRoleCheck.bypass_reasons(connection)
    end
  end

  test "the check rejects a role that owns a table and nothing more" do
    as_superuser do |connection|
      connection.execute("CREATE ROLE #{PROBE_ROLE}")
      connection.execute("CREATE TABLE role_check_probes (id bigint)")
      connection.execute("ALTER TABLE role_check_probes OWNER TO #{PROBE_ROLE}")
      log_in_as(connection, PROBE_ROLE)

      assert_equal [ "it owns, or is a member of the owner of, 1 table (public.role_check_probes)" ],
        Tenancy::DatabaseRoleCheck.bypass_reasons(connection)
    end
  end

  test "the check rejects a member of the owner role" do
    as_superuser do |connection|
      connection.execute("CREATE ROLE #{PROBE_ROLE} IN ROLE footsoldier_owner")
      log_in_as(connection, PROBE_ROLE)

      reasons = Tenancy::DatabaseRoleCheck.bypass_reasons(connection)
      assert_includes reasons, "it is a member of footsoldier_owner, which can bypass it"
      assert reasons.any? { it.start_with?("it owns, or is a member of the owner of,") }, reasons.inspect
    end
  end

  test "the app role reads and writes tables the owner creates later, but cannot create or truncate tables" do
    as_superuser do |connection|
      log_in_as(connection, "footsoldier_owner")
      connection.execute("CREATE TABLE role_check_probes (id bigint GENERATED BY DEFAULT AS IDENTITY, name text)")
      log_in_as(connection, "footsoldier_app")

      connection.execute("INSERT INTO role_check_probes (name) VALUES ('one'), ('two')")
      connection.execute("UPDATE role_check_probes SET name = 'three' WHERE name = 'two'")
      connection.execute("DELETE FROM role_check_probes WHERE name = 'one'")
      assert_equal [ "three" ], connection.select_values("SELECT name FROM role_check_probes")

      [ "CREATE TABLE app_role_tables (id bigint)", "TRUNCATE role_check_probes" ].each do |statement|
        error = assert_raises(ActiveRecord::StatementInvalid) do
          connection.transaction(requires_new: true) { connection.execute(statement) }
        end
        assert_match "permission denied", error.message
      end
    end
  end

  private
    def connect(config)
      ActiveRecord::ConnectionAdapters::PostgreSQLAdapter.new(config).tap { @connections << it }
    end

    # libpq's default role: the OS user locally, PGUSER in CI. bin/setup and CI create the
    # database roles with it, so it is a superuser wherever they have run.
    def superuser_connection
      config = ActiveRecord::Base.connection_db_config.configuration_hash.except(:username, :password)
      connection = connect(config)
      unless connection.select_value("SELECT rolsuper FROM pg_roles WHERE rolname = session_user")
        skip "needs libpq's default role, #{connection.select_value("SELECT session_user")}, to be a superuser"
      end
      connection
    end

    # Runs the block on a superuser connection in a transaction that is rolled back, together with
    # the roles, tables and session changes the block makes.
    def as_superuser
      connection = superuser_connection
      connection.transaction do
        yield connection
        raise ActiveRecord::Rollback
      end
    end

    # Makes the rest of the transaction run as the role, as if the connection had logged in as it.
    def log_in_as(connection, role)
      connection.execute("SET LOCAL SESSION AUTHORIZATION #{connection.quote_column_name(role)}")
    end
end
